-- Phase 2e step 2: the Trading Hall, where players list goods at their own price.
--  * List for 2, 8 or 24 hours. The deposit is 1%, 2% or 3% of the asking total. It comes back when the goods sell
--    and is lost when they do not. The Hall keeps 5% of every sale.
--  * Prices must sit between half and four times the fair price.
--  * Trading with other players opens 3 days after you join, once any skill reaches Lv 10.
--  * Every sale goes in the sale log. Sales between two accounts on one connection, and repeat sales between the
--    same two players, are marked and do not count toward prices.
create table if not exists public.os_hall (
  id bigint generated by default as identity primary key,
  seller uuid not null references public.os_player(uid) on delete cascade,
  item_id text not null references public.os_item_def(id),
  qty int not null check (qty > 0),
  left_qty int not null check (left_qty >= 0),
  unit bigint not null check (unit > 0),
  hours int not null check (hours in (2, 8, 24)),
  deposit bigint not null default 0,
  deposit_left bigint not null default 0,
  ip text,
  status text not null default 'open' check (status in ('open', 'sold', 'expired', 'cancelled')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists os_hall_open on public.os_hall(item_id, unit) where status = 'open';
create index if not exists os_hall_seller on public.os_hall(seller) where status = 'open';
create index if not exists os_hall_expiry on public.os_hall(expires_at) where status = 'open';
alter table public.os_hall enable row level security;
revoke all on public.os_hall from anon, authenticated;

-- A one-way fingerprint of the connection, so two accounts on one device can be spotted without keeping the address.
create or replace function public.os_req_ip() returns text
language sql stable set search_path to 'public' as $f$
  select nullif(md5(coalesce(split_part(coalesce(current_setting('request.headers', true)::json->>'x-forwarded-for', ''), ',', 1), '') || ':os'), md5(':os'));
$f$;
revoke all on function public.os_req_ip() from public, anon, authenticated;

-- Can this player trade with other players yet? 3 days in the city and Lv 10 in any skill.
create or replace function public.os_can_trade(p_uid uuid) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $f$
declare p os_player; best int := 1; k text; v jsonb; opens timestamptz;
begin
  select * into p from os_player where uid = p_uid;
  if not found then return jsonb_build_object('ok', false); end if;
  for k, v in select key, value from jsonb_each(coalesce(p.skill, '{}'::jsonb)) loop
    if jsonb_typeof(v) = 'object' and v ? 'xp' then best := greatest(best, os_skill_level((v->>'xp')::int)); end if;
  end loop;
  opens := p.created_at + interval '3 days';
  return jsonb_build_object('ok', not coalesce(p.banned, false) and now() >= opens and best >= 10,
    'opens', opens, 'days', now() >= opens, 'level', best >= 10, 'best', best);
end $f$;
revoke all on function public.os_can_trade(uuid) from public, anon, authenticated;

-- Goods whose time ran out go back to their seller. The deposit stays with the Hall.
create or replace function public.os_hall_sweep() returns int
language plpgsql security definer set search_path to 'public' as $f$
declare r record; n int := 0;
begin
  for r in select * from os_hall where status = 'open' and expires_at <= now() order by id for update skip locked loop
    perform os_give(r.seller, r.item_id, r.left_qty);
    update os_hall set status = 'expired', deposit_left = 0 where id = r.id;
    n := n + 1;
  end loop;
  return n;
end $f$;
revoke all on function public.os_hall_sweep() from public, anon, authenticated;

-- The fair price follows real sales. Step 3 fills this in; until then it keeps the price we set.
create or replace function public.os_fair_update(p_item text) returns void
language plpgsql security definer set search_path to 'public' as $f$ begin return; end $f$;
revoke all on function public.os_fair_update(text) from public, anon, authenticated;

create or replace function public.os_hall_act(op text, payload jsonb) returns jsonb
language plpgsql security definer set search_path to 'public' as $f$
declare
  u uuid := auth.uid(); f os_fair; d os_item_def; h os_hall; ct jsonb;
  v_item text; v_qty int; v_unit bigint; v_hours int; v_dep bigint; v_have int; v_cost bigint; v_cut bigint; v_back bigint;
  v_ip text := os_req_ip(); v_flag text; v_open int;
begin
  if u is null or not os_ok() then raise exception 'not allowed'; end if;
  perform os_tick(u);
  perform os_hall_sweep();
  if op in ('list', 'buy') then
    ct := os_can_trade(u);
    if not (ct->>'ok')::boolean then raise exception 'Trading with other players opens 3 days after you arrive, once any skill reaches Lv 10.'; end if;
  end if;

  if op = 'list' then
    v_item := payload->>'item';
    v_qty := coalesce((payload->>'qty')::int, 1);
    v_unit := coalesce((payload->>'unit')::bigint, 0);
    v_hours := coalesce((payload->>'hours')::int, 8);
    if v_hours not in (2, 8, 24) then raise exception 'Pick 2, 8 or 24 hours.'; end if;
    select * into d from os_item_def where id = v_item;
    select * into f from os_fair where item_id = v_item;
    if d.id is null or f.item_id is null or d.owner_uid is not null or d.bind = 'pickup' then raise exception 'The Hall does not take that.'; end if;
    if v_qty < 1 then raise exception 'List at least one.'; end if;
    if v_unit < greatest(1, ceil(f.fair * 0.5)) or v_unit > f.fair * 4 then
      raise exception 'Set a price between half and four times the fair price.';
    end if;
    select count(*) into v_open from os_hall where seller = u and status = 'open';
    if v_open >= 20 then raise exception 'You already have 20 goods up in the Hall.'; end if;
    select qty into v_have from os_bag where uid = u and item_id = v_item for update;
    if coalesce(v_have, 0) < v_qty then raise exception 'You do not have that many.'; end if;
    v_dep := greatest(1, ceil(v_unit * v_qty * case v_hours when 2 then 0.01 when 8 then 0.02 else 0.03 end))::bigint;
    perform os_wallet(u, -v_dep);
    perform os_give(u, v_item, -v_qty);
    insert into os_hall(seller, item_id, qty, left_qty, unit, hours, deposit, deposit_left, ip, expires_at)
    values (u, v_item, v_qty, v_qty, v_unit, v_hours, v_dep, v_dep, v_ip, now() + make_interval(hours => v_hours))
    returning * into h;
    insert into os_event(uid, kind, qty, ref) values (u, 'hall_list', v_qty, v_item);

  elsif op = 'buy' then
    select * into h from os_hall where id = (payload->>'id')::bigint for update;
    if h.id is null or h.status <> 'open' or h.expires_at <= now() then raise exception 'Someone got there first.'; end if;
    if h.seller = u then raise exception 'That is your own listing.'; end if;
    v_qty := least(h.left_qty, greatest(1, coalesce((payload->>'qty')::int, h.left_qty)));
    v_cost := h.unit * v_qty;
    perform os_wallet(u, -v_cost);
    v_cut := round(v_cost * 0.05)::bigint;
    v_back := case when v_qty = h.left_qty then h.deposit_left else least(h.deposit_left, floor(h.deposit::numeric * v_qty / h.qty)::bigint) end;
    perform os_wallet(h.seller, v_cost - v_cut + v_back);
    perform os_give(u, h.item_id, v_qty);
    update os_hall set left_qty = left_qty - v_qty, deposit_left = deposit_left - v_back,
      status = case when left_qty - v_qty <= 0 then 'sold' else 'open' end where id = h.id;
    v_flag := case
      when v_ip is not null and v_ip = h.ip then 'same_device'
      when (select count(*) from os_trade t where t.source = 'hall' and t.created_at > now() - interval '1 day'
              and ((t.seller = h.seller and t.buyer = u) or (t.seller = u and t.buyer = h.seller))) >= 2 then 'repeat'
      else null end;
    insert into os_trade(item_id, price, qty, source, seller, buyer, unit, flag)
    values (h.item_id, greatest(1, round(h.unit / 10000.0))::int, v_qty, 'hall', h.seller, u, h.unit, v_flag);
    insert into os_event(uid, kind, qty, ref) values (u, 'hall_buy', v_qty, h.item_id), (h.seller, 'hall_sold', v_qty, h.item_id);
    perform os_fair_update(h.item_id);

  elsif op = 'cancel' then
    select * into h from os_hall where id = (payload->>'id')::bigint and seller = u for update;
    if h.id is null or h.status <> 'open' then raise exception 'That listing is already gone.'; end if;
    perform os_give(u, h.item_id, h.left_qty);
    update os_hall set status = 'cancelled', deposit_left = 0 where id = h.id;

  else
    raise exception 'not allowed';
  end if;
  return os_pack(u);
end $f$;
revoke all on function public.os_hall_act(text, jsonb) from public, anon;
grant execute on function public.os_hall_act(text, jsonb) to authenticated;

-- Seven days of sales for one good: average price, how many sold, and the fair price each day.
create or replace function public.os_price_history(i text) returns jsonb
language plpgsql stable security definer set search_path to 'public' as $f$
begin
  if auth.uid() is null or not os_ok() then raise exception 'not allowed'; end if;
  return jsonb_build_object(
    'item', i,
    'fair', (select fair from os_fair where item_id = i),
    'low', (select min(unit) from os_hall where item_id = i and status = 'open' and expires_at > now()),
    'days', coalesce((select jsonb_agg(jsonb_build_object('day', g.d, 'avg', x.avg, 'sold', coalesce(x.sold, 0), 'fair', null) order by g.d)
      from generate_series(current_date - 6, current_date, interval '1 day') g(d)
      left join (select created_at::date d, round(sum(unit * qty)::numeric / nullif(sum(qty), 0))::bigint avg, sum(qty)::int sold
                 from os_trade where item_id = i and source in ('hall', 'trader') and flag is null and created_at > current_date - 7 group by 1) x on x.d = g.d::date
      ), '[]'::jsonb),
    'avg', (select round(sum(unit * qty)::numeric / nullif(sum(qty), 0))::bigint from os_trade where item_id = i and source in ('hall', 'trader') and flag is null and created_at > now() - interval '7 days'),
    'sold', (select coalesce(sum(qty), 0) from os_trade where item_id = i and source in ('hall', 'trader') and flag is null and created_at > now() - interval '7 days')
  );
end $f$;
revoke all on function public.os_price_history(text) from public, anon;
grant execute on function public.os_price_history(text) to authenticated;

-- The market part of the state: fair prices, the Hall, your own listings and whether you can trade yet.
create or replace function public.os_market_pack(p_uid uuid)
 returns jsonb language sql stable security definer set search_path to 'public'
as $function$
  select jsonb_build_object(
    'fair', coalesce((select jsonb_object_agg(f.item_id, f.fair) from os_fair f), '{}'::jsonb),
    'listings', coalesce((select jsonb_agg(jsonb_build_object('id', l.id, 'item', l.item_id, 'price', l.price, 'qty', l.qty, 'today', 0, 'kind', l.kind, 'hero_id', l.hero_id)) from os_listing l where l.kind = 'item'), '[]'::jsonb),
    'cards', coalesce((select jsonb_agg(jsonb_build_object('id', l.id, 'hero', l.hero_id, 'level', coalesce(l.hero_level,1), 'seller', coalesce(sp.name,'a trader'), 'price', l.price)) from os_listing l left join os_player sp on sp.uid = l.seller where l.kind = 'card'), '[]'::jsonb),
    'hall', coalesce((select jsonb_agg(jsonb_build_object('id', h.id, 'item', h.item_id, 'qty', h.left_qty, 'unit', h.unit, 'seller', coalesce(sp.name, 'a trader'), 'until', h.expires_at, 'mine', h.seller = p_uid) order by h.item_id, h.unit, h.id)
      from (select * from os_hall where status = 'open' and expires_at > now() order by unit limit 200) h left join os_player sp on sp.uid = h.seller), '[]'::jsonb),
    'mine', coalesce((select jsonb_agg(jsonb_build_object('id', h.id, 'item', h.item_id, 'qty', h.qty, 'left', h.left_qty, 'unit', h.unit, 'until', h.expires_at, 'status', h.status, 'deposit', h.deposit) order by h.id desc)
      from (select * from os_hall where seller = p_uid and (status = 'open' or created_at > now() - interval '2 days') order by id desc limit 30) h), '[]'::jsonb),
    'trade', public.os_can_trade(p_uid)
  );
$function$;
revoke all on function public.os_market_pack(uuid) from public, anon, authenticated;

-- Goods whose time ran out go home whenever their owner looks.
CREATE OR REPLACE FUNCTION public.os_pack(p_uid uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare p public.os_player; welcome jsonb;
begin
  perform public.os_hall_sweep();
  select * into p from os_player where uid = p_uid;
  if p.pending is not null and p.pending->'items' is not null then
    select jsonb_build_object(
      'away', coalesce(p.pending->>'away','a while'),
      'lines', coalesce(jsonb_agg(jsonb_build_object(
        'icon','chest','text', i.name || ' came in','value','+' || e.value,'cls','lm')), '[]'::jsonb)
    ) into welcome
    from jsonb_each_text(p.pending->'items') e
    join os_item_def i on i.id = e.key;
  end if;
  return jsonb_build_object(
    'now', now(),
    'player', (select to_jsonb(x) from os_player x where x.uid = p_uid),
    'heroes', coalesce((select jsonb_agg(to_jsonb(h)) from os_hero h where h.uid = p_uid), '[]'::jsonb),
    'bag', coalesce((select jsonb_agg(jsonb_build_object('id', b.item_id, 'qty', b.qty)) from os_bag b where b.uid = p_uid), '[]'::jsonb),
    'delve', (select to_jsonb(d) from os_delve d where d.uid = p_uid),
    'known', coalesce((select jsonb_agg(hd.id) from os_hero_def hd where hd.found and hd.owner_uid is null), '[]'::jsonb),
    'feed', coalesce((select jsonb_agg(f.msg) from (select msg from os_feed order by id desc limit 8) f), '[]'::jsonb),
    'crier', coalesce((select jsonb_agg(jsonb_build_object('tag', coalesce(c.tag,'Streets'), 'msg', c.msg, 'at', c.at) order by c.id desc) from (select * from os_feed order by id desc limit 20) c), '[]'::jsonb),
    'welcome', welcome,
    'gear', coalesce((select jsonb_object_agg(x.hero_id, x.g) from (select g.hero_id, jsonb_object_agg(g.slot, g.item_id) g from os_gear g where g.uid = p_uid group by g.hero_id) x), '{}'::jsonb),
    'stats', coalesce((select jsonb_object_agg(h.hero_id, public.os_hero_stats(p_uid, h.hero_id)) from os_hero h where h.uid = p_uid), '{}'::jsonb),
    'market', public.os_market_pack(p_uid),
    'config', coalesce((select jsonb_object_agg(key, value) from os_config), '{}'::jsonb),
    'infirmary', coalesce((select jsonb_agg(jsonb_build_object('id', hero_id, 'name', hero_id, 'reason', reason, 'until', until)) from os_infirmary where uid = p_uid and until > now()), '[]'::jsonb),
    'crew', (
      select jsonb_build_object(
        'name', c.name, 'rank', 1, 'members', (select count(*) from os_crew_member mm where mm.crew_id = c.id),
        'max', 25, 'online', 1, 'perk', '+5% XP', 'vaultOre', coalesce((c.vault->>'moonsilver_ore')::int, c.goal_have),
        'goal', c.goal_need, 'youGave', c.goal_have, 'motto', coalesce(c.motto,''), 'code', c.code,
        'roster', coalesce((select jsonb_agg(jsonb_build_object('name', pp.name, 'role', mm.role, 'line', 'In the city', 'on', true, 'face', 'engineer')) from os_crew_member mm join os_player pp on pp.uid = mm.uid where mm.crew_id = c.id), '[]'::jsonb),
        'chat', coalesce((select jsonb_agg(jsonb_build_object('who', coalesce(pp.name,'Crew'), 'face', 'engineer', 'color', 'cy', 't', to_char(ch.created_at, 'HH12:MI PM'), 'text', ch.body) order by ch.id) from os_chat ch left join os_player pp on pp.uid = ch.uid where ch.crew_id = c.id), '[]'::jsonb),
        'cup', coalesce((select jsonb_agg(jsonb_build_array(cc.name, cc.cup) order by cc.cup desc) from os_crew cc), '[]'::jsonb),
        'raid', 'The Hollow Bishop', 'raidN', 0
      )
      from os_crew c
      join os_crew_member me on me.crew_id = c.id and me.uid = p_uid
    )
  );
end $function$;

